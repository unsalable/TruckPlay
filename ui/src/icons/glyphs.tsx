// Gear outline generated once: rounded teeth around a ring with a hole.
function gearPath(teeth: number, outer: number, inner: number, hole: number, c = 12): string {
  const pts: string[] = [];
  const step = (Math.PI * 2) / teeth;
  for (let i = 0; i < teeth; i++) {
    const a = i * step - Math.PI / 2;
    const p = (angle: number, r: number) => `${(c + Math.cos(angle) * r).toFixed(3)} ${(c + Math.sin(angle) * r).toFixed(3)}`;
    pts.push(`${i === 0 ? 'M' : 'L'}${p(a - step * 0.28, inner)}`);
    pts.push(`L${p(a - step * 0.17, outer)}`);
    pts.push(`L${p(a + step * 0.17, outer)}`);
    pts.push(`L${p(a + step * 0.28, inner)}`);
  }
  const holeD = `M${c + hole} ${c}a${hole} ${hole} 0 1 0 ${-hole * 2} 0a${hole} ${hole} 0 1 0 ${hole * 2} 0z`;
  return `${pts.join('')}Z${holeD}`;
}

