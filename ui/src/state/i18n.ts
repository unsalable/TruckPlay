export type Lang = 'tr' | 'en';
const tables: Record<Lang, Record<StringKey, string>> = { tr, en };

export const language = createStore<Lang>('tr');

export function t(key: StringKey, lang: Lang = language.get()): string {
  return tables[lang][key] ?? key;
}

export function useT(): (key: StringKey) => string {
  const lang = useStore(language, l => l);
  return (key: StringKey) => t(key, lang);
}
