/// Turkish, unless Windows' own language is something else (TRUCKPLAY_SETUP_LANG=tr|en decides
/// instead, for trying both).
pub fn text() -> &'static Text {
    const LANG_TURKISH: u16 = 0x1f;
    match std::env::var("TRUCKPLAY_SETUP_LANG").as_deref() {
        Ok("tr") => return &TR,
        Ok("en") => return &EN,
        _ => {}
    }
    // SAFETY: a plain query of the user's UI language.
    let lang = unsafe { GetUserDefaultUILanguage() };
    if lang & 0x3ff == LANG_TURKISH { &TR } else { &EN }
}
